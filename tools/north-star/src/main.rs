//! DOCS-03: `north-star <store.meta> <out.md>` writes docs/spec/NORTH-STAR.md from
//! the newest north star in Ishoo's store (refs/ishoo/store:.ishoo/store.meta, a
//! zstd-compressed TOML record), so the file never drifts from Ishoo.
use serde::Deserialize;
use std::fmt::Write as _;

#[derive(Deserialize)]
struct Meta {
    record: Record,
}

#[derive(Deserialize)]
struct Record {
    north_star: History,
}

#[derive(Deserialize)]
struct History {
    versions: Vec<Version>,
}

#[derive(Deserialize)]
struct Version {
    version: u32,
    recorded_at: String,
    north_star: NorthStar,
}

#[derive(Deserialize)]
struct NorthStar {
    promise: String,
    ambition: String,
    tests: Vec<String>,
    stops: String,
    bar: String,
}

fn render(v: &Version) -> String {
    let ns = &v.north_star;
    let date = v.recorded_at.get(..10).unwrap_or(&v.recorded_at);
    let mut out = String::new();
    writeln!(out, "# North Star\n").unwrap();
    writeln!(
        out,
        "<!-- Generated by .github/workflows/north-star.yml (tools/north-star) from \
         refs/ishoo/store. Do not edit: change the north star in Ishoo. -->\n"
    )
    .unwrap();
    writeln!(
        out,
        "This is the project north star held in Ishoo (`ishoo_north_star op:show`), \
         version {}, set {date}. Earlier versions are in `ishoo_north_star op:history`.\n",
        v.version
    )
    .unwrap();
    writeln!(out, "## Promise\n\n{}\n", ns.promise).unwrap();
    writeln!(out, "## Ambition\n\n{}\n", ns.ambition).unwrap();
    writeln!(out, "## Tests\n\nEvery idea must pass all of these, in order, to belong:\n").unwrap();
    for (i, test) in ns.tests.iter().enumerate() {
        writeln!(out, "{}. {test}", i + 1).unwrap();
    }
    writeln!(out, "\n## Where it stops\n\n{}\n", ns.stops).unwrap();
    write!(out, "## The bar\n\n{}\n", ns.bar).unwrap();
    out
}

fn run(meta: &str, out: &str) -> Result<(), String> {
    let bytes = std::fs::read(meta).map_err(|e| format!("{meta}: {e}"))?;
    let text = zstd::decode_all(bytes.as_slice()).map_err(|e| format!("{meta}: zstd: {e}"))?;
    let text = String::from_utf8(text).map_err(|e| format!("{meta}: {e}"))?;
    let meta: Meta = toml::from_str(&text).map_err(|e| format!("store.meta: {e}"))?;
    let newest = meta
        .record
        .north_star
        .versions
        .iter()
        .max_by_key(|v| v.version)
        .ok_or("store.meta has no north star versions")?;
    std::fs::write(out, render(newest)).map_err(|e| format!("{out}: {e}"))
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [meta, out] = args.as_slice() else {
        eprintln!("usage: north-star <store.meta> <out.md>");
        std::process::exit(2);
    };
    if let Err(e) = run(meta, out) {
        eprintln!("north-star: {e}");
        std::process::exit(1);
    }
}
